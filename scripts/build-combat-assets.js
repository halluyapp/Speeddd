function node(parent, name, role, position, extras = {}) {
  const object = new THREE.Group(); object.name = name; object.position.copy(position); object.userData = { velocityRole: role, ...extras }; parent.add(object); return object;
}
function boltRing(batch, detail, radius, y, count = 8) {
  if (!detail.bolts) return;
  for (let index = 0; index < count; index += 1) {
    const angle = index / count * Math.PI * 2;
    batch.cylinder('fasteners', MAT.metal, [0.045, 0.045], 0.055, 8, v(Math.sin(angle) * radius, y, Math.cos(angle) * radius));
  }
}
function cable(batch, detail, points, radius = 0.025) {
  if (detail.cables) batch.tube('cabling', MAT.rubber, points, radius, detail.segments);
}
function brace(batch, from, to, radius, segments, mat = MAT.metal) {
  const direction = to.clone().sub(from);
  const geometry = new THREE.CylinderGeometry(radius, radius, direction.length(), segments);
  const quaternion = new THREE.Quaternion().setFromUnitVectors(v(0, 1, 0), direction.clone().normalize());
  const matrix = new THREE.Matrix4().compose(from.clone().add(to).multiplyScalar(0.5), quaternion, v(1, 1, 1));
  batch.add('structure', mat, geometry, matrix); geometry.dispose();
}

function turretRig(definition, detail) {
  const scene = new THREE.Scene(); scene.name = definition.name;
  const root = node(scene, 'WeaponRoot', 'weapon-root', v(0, 0, 0), { mountConvention: 'roof-ring-ground-zero' });
  node(root, 'MountSocket', 'mount-socket', v(0, 0, 0), { mountType: 'roof-ring', upAxis: [0, 1, 0], forwardAxis: [0, 0, 1] });
  const base = new GeometryBatch(root);
  base.box('mount', MAT.dark, [1.28, 0.12, 1.38], v(0, 0.06, 0), noRotation, detail.bevel);
  base.cylinder('mount', MAT.armor, [0.64, 0.7], 0.18, detail.segments, v(0, 0.19, 0));
  base.torus('mount', MAT.metal, 0.53, 0.045, detail.segments, v(0, 0.29, 0), new THREE.Euler(Math.PI / 2, 0, 0));
  base.box('mount', MAT.rubber, [1.08, 0.035, 1.18], v(0, 0.015, 0));
  boltRing(base, detail, 0.53, 0.32);

  const yaw = node(root, 'YawPivot', 'yaw-pivot', v(0, 0.3, 0), { axis: [0, 1, 0], minDegrees: definition.yawRange[0], maxDegrees: definition.yawRange[1] });
  const yawBatch = new GeometryBatch(yaw);
  yawBatch.cylinder('yaw-drive', MAT.dark, [0.39, 0.43], 0.44, detail.segments, v(0, 0.22, 0));
  yawBatch.torus('yaw-drive', MAT.lime, 0.4, 0.025, detail.segments, v(0, 0.34, 0), new THREE.Euler(Math.PI / 2, 0, 0));
  const support = definition.support ?? 0.62;
  for (const side of [-1, 1]) {
    yawBatch.box('cradle', MAT.armor, [0.17, 0.67, 0.6], v(side * support, 0.43, -0.05), noRotation, detail.bevel);
    yawBatch.cylinder('trunnion', MAT.metal, [0.16, 0.16], 0.22, detail.segments, v(side * support, 0.72, 0), new THREE.Euler(0, 0, Math.PI / 2));
    if (detail.bolts) yawBatch.cylinder('fasteners', MAT.dark, [0.065, 0.065], 0.235, 8, v(side * support, 0.72, 0), new THREE.Euler(0, 0, Math.PI / 2));
  }
  const pitch = node(yaw, 'PitchPivot', 'pitch-pivot', v(0, 0.72, 0), { axis: [1, 0, 0], minDegrees: definition.pitchRange[0], maxDegrees: definition.pitchRange[1], positiveRaisesMuzzle: true });
  const pitchBatch = new GeometryBatch(pitch);
  return { scene, root, yaw, pitch, base, yawBatch, pitchBatch, batches: [base, yawBatch, pitchBatch], spin: null, spinBatch: null };
}
function finishTurret(rig, definition) {
  const parent = rig.spin || rig.pitch;
  definition.muzzles.forEach((position, index) => {
    const marker = node(parent, `MuzzleSocket_${String(index).padStart(2, '0')}`, 'muzzle-socket', v(...position), { muzzleIndex: index, direction: [0, 0, 1], localSpace: rig.spin ? 'spin-pivot' : 'pitch-pivot' });
    marker.rotation.set(0, 0, 0);
  });
  rig.batches.forEach((batch) => batch.flush());
  return rig.scene;
}
function panelBolts(batch, detail, xs, y, z) {
  if (!detail.bolts) return;
  for (const x of xs) batch.zCylinder('fasteners', MAT.metal, [0.035, 0.035], 0.04, 8, v(x, y, z));
}

