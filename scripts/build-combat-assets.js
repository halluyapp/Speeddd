class GeometryBatch {
  constructor(parent) { this.parent = parent; this.batches = new Map(); }
  add(role, mat, geometry, matrix = new THREE.Matrix4()) {
    const transformed = geometry.index ? geometry.toNonIndexed() : geometry.clone();
    transformed.applyMatrix4(matrix);
    if (!transformed.getAttribute('normal')) transformed.computeVertexNormals();
    if (!transformed.getAttribute('uv')) transformed.setAttribute('uv', new THREE.Float32BufferAttribute(new Float32Array(transformed.getAttribute('position').count * 2), 2));
    const key = `${role}:${mat.uuid}`;
    if (!this.batches.has(key)) this.batches.set(key, { role, mat, geometries: [] });
    this.batches.get(key).geometries.push(transformed);
  }
  matrix(position, rotation = new THREE.Euler()) { return new THREE.Matrix4().compose(position, new THREE.Quaternion().setFromEuler(rotation), new THREE.Vector3(1, 1, 1)); }
  box(role, mat, size, position, rotation = new THREE.Euler(), bevel = 0) {
    const geometry = bevel > 0 ? new RoundedBoxGeometry(...size, bevel, Math.min(...size) * 0.12) : new THREE.BoxGeometry(...size);
    this.add(role, mat, geometry, this.matrix(position, rotation)); geometry.dispose();
  }
  cylinder(role, mat, radii, height, segments, position, rotation = new THREE.Euler()) {
    const geometry = new THREE.CylinderGeometry(radii[0], radii[1], height, segments, 1, false);
    this.add(role, mat, geometry, this.matrix(position, rotation)); geometry.dispose();
  }
  zCylinder(role, mat, radii, height, segments, position) {
    this.cylinder(role, mat, radii, height, segments, position, new THREE.Euler(Math.PI / 2, 0, 0));
  }
  torus(role, mat, radius, tube, segments, position, rotation = new THREE.Euler()) {
    const geometry = new THREE.TorusGeometry(radius, tube, Math.max(4, Math.floor(segments / 4)), segments);
    this.add(role, mat, geometry, this.matrix(position, rotation)); geometry.dispose();
  }
  tube(role, mat, points, radius, segments) {
    const curve = new THREE.CatmullRomCurve3(points);
    const geometry = new THREE.TubeGeometry(curve, Math.max(5, segments), radius, segments >= 20 ? 8 : 5, false);
    this.add(role, mat, geometry); geometry.dispose();
  }
  flush() {
    for (const { role, mat, geometries } of this.batches.values()) {
      const merged = mergeGeometries(geometries, false);
      if (!merged) throw new Error(`Unable to merge ${role}/${mat.name}`);
      const mesh = new THREE.Mesh(merged, mat);
      mesh.name = `${role}__${mat.name.replaceAll(' ', '_')}`;
      mesh.userData.velocityRole = role;
      this.parent.add(mesh);
      geometries.forEach((geometry) => geometry.dispose());
    }
    this.batches.clear();
  }
}

