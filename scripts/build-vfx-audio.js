async function buildEffect(effect) {
  const frames = [];
  let thumbnail;
  const thumbnailFrame = effect.frames === 1 ? 0 : Math.floor(effect.frames * 0.55);
  for (let frame = 0; frame < effect.frames; frame += 1) {
    const svg = effect.svg(frame, effect.frames, rngFactory(effect.seed));
    const png = await sharp(Buffer.from(svg)).png().toBuffer();
    frames.push({ input: png, left: (frame % effect.columns) * effect.width, top: Math.floor(frame / effect.columns) * effect.height });
    if (frame === thumbnailFrame) thumbnail = await sharp(png).resize(180, 180, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } }).webp({ quality: 88 }).toBuffer();
  }
  const atlasWidth = effect.columns * effect.width;
  const atlasHeight = effect.rows * effect.height;
  const master = await sharp({ create: { width: atlasWidth, height: atlasHeight, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } } }).composite(frames).png().toBuffer();
  const masterRelative = `assets-src/vfx/${effect.id}.png`;
  const runtimeRelative = `assets/vfx/flipbooks/${effect.id}.webp`;
  const thumbnailRelative = `assets/vfx/thumbnails/${effect.id}.webp`;
  await fs.writeFile(path.join(ROOT, masterRelative), master);
  await sharp(master).webp({ quality: 90, alphaQuality: 95, effort: 4 }).toFile(path.join(ROOT, 'public', runtimeRelative));
  await fs.writeFile(path.join(ROOT, 'public', thumbnailRelative), thumbnail);
  return {
    id: effect.id, name: effect.name, category: effect.category, type: effect.decal ? 'decal' : effect.frames > 1 ? 'flipbook' : 'sprite',
    master: masterRelative, runtime: runtimeRelative, thumbnail: thumbnailRelative,
    frames: effect.frames, columns: effect.columns, rows: effect.rows, frameWidth: effect.width, frameHeight: effect.height,
    atlasWidth, atlasHeight, fps: effect.fps, duration: effect.fps ? round(effect.frames / effect.fps) : 0,
    loop: effect.loop, blend: effect.blend, decal: Boolean(effect.decal), suggestedSize: effect.size,
    license: 'CC0-1.0', bytes: (await fs.stat(path.join(ROOT, 'public', runtimeRelative))).size,
  };
}

