function synthesize(definition) {
  const fade = definition.loop ? Math.min(0.25, definition.duration * 0.1) : 0;
  const rawLength = Math.round((definition.duration + fade) * MASTER_RATE);
  const raw = [new Float32Array(rawLength), new Float32Array(rawLength)];
  const random = rngFactory(definition.seed);
  let lowL = 0; let lowR = 0; let slowL = 0; let slowR = 0; let phase = 0;
  for (let i = 0; i < rawLength; i += 1) {
    const t = i / MASTER_RATE;
    const p = clamp(t / definition.duration);
    const noiseL = random() * 2 - 1;
    const noiseR = random() * 2 - 1;
    lowL += 0.08 * (noiseL - lowL); lowR += 0.08 * (noiseR - lowR);
    slowL += 0.006 * (noiseL - slowL); slowR += 0.006 * (noiseR - slowR);
    let left = 0; let right = 0;
    if (definition.id === 'engine-idle-loop' || definition.id === 'engine-high-loop') {
      const high = definition.id === 'engine-high-loop';
      const base = high ? 118 : 43;
      const frequency = base * (1 + 0.025 * Math.sin(2 * Math.PI * (high ? 0.75 : 1.25) * t));
      phase += 2 * Math.PI * frequency / MASTER_RATE;
      const pulse = Math.sin(phase) + 0.48 * Math.sin(phase * 2 + 0.2) + 0.25 * Math.sin(phase * 3) + 0.13 * Math.sin(phase * 4.02);
      const combustion = Math.pow((Math.sin(phase * 0.5) + 1) * 0.5, 5) * 0.28;
      const mechanical = Math.sin(2 * Math.PI * (high ? 1380 : 310) * t) * (high ? 0.035 : 0.02);
      left = pulse * (high ? 0.23 : 0.3) + combustion + mechanical + lowL * 0.15;
      right = pulse * (high ? 0.22 : 0.29) + combustion + mechanical + lowR * 0.15;
    } else if (definition.id === 'tire-skid-loop') {
      const scrub = 0.75 + 0.18 * Math.sin(2 * Math.PI * 1.3 * t) + 0.08 * Math.sin(2 * Math.PI * 7.1 * t);
      left = ((noiseL - lowL) * 0.42 + Math.sin(2 * Math.PI * 740 * t + Math.sin(t * 4)) * 0.055) * scrub;
      right = ((noiseR - lowR) * 0.42 + Math.sin(2 * Math.PI * 770 * t + Math.sin(t * 4.3)) * 0.055) * scrub;
    } else if (definition.id === 'coastal-wind-loop') {
      const gust = 0.55 + 0.22 * Math.sin(2 * Math.PI * 0.17 * t) + 0.13 * Math.sin(2 * Math.PI * 0.41 * t + 1);
      left = (slowL * 1.5 + lowL * 0.28 + Math.sin(2 * Math.PI * 52 * t) * 0.018) * gust;
      right = (slowR * 1.5 + lowR * 0.28 + Math.sin(2 * Math.PI * 49 * t + 0.4) * 0.018) * gust;
    } else if (definition.id === 'boost-surge') {
      const envelope = Math.sin(Math.PI * p) ** 0.7 * (1 - p * 0.25);
      phase += 2 * Math.PI * (110 + 1050 * p * p) / MASTER_RATE;
      left = (Math.sin(phase) * 0.24 + (noiseL - lowL) * 0.28 + lowL * 0.3) * envelope;
      right = (Math.sin(phase + 0.04) * 0.24 + (noiseR - lowR) * 0.28 + lowR * 0.3) * envelope;
    } else if (definition.id === 'gear-shift') {
      const hit = Math.exp(-t * 16);
      const click = Math.exp(-t * 55);
      left = Math.sin(2 * Math.PI * 105 * t) * hit * 0.55 + noiseL * click * 0.4 + Math.sin(2 * Math.PI * 690 * t) * Math.exp(-t * 9) * 0.12;
      right = Math.sin(2 * Math.PI * 105 * t + 0.05) * hit * 0.55 + noiseR * click * 0.4 + Math.sin(2 * Math.PI * 730 * t) * Math.exp(-t * 9) * 0.12;
    } else if (definition.id === 'heavy-impact' || definition.id === 'explosion') {
      const explosion = definition.id === 'explosion';
      const decay = Math.exp(-t * (explosion ? 2.1 : 4.2));
      const crack = Math.exp(-t * (explosion ? 28 : 45));
      left = Math.sin(2 * Math.PI * (explosion ? 43 : 68) * t) * decay * (explosion ? 0.75 : 0.6) + noiseL * crack * 0.75 + lowL * decay * 0.75 + Math.sin(2 * Math.PI * 510 * t) * Math.exp(-t * 7) * 0.12;
      right = Math.sin(2 * Math.PI * (explosion ? 43 : 68) * t + 0.04) * decay * (explosion ? 0.75 : 0.6) + noiseR * crack * 0.75 + lowR * decay * 0.75 + Math.sin(2 * Math.PI * 560 * t) * Math.exp(-t * 7) * 0.12;
    } else if (definition.id === 'race-countdown') {
      const envelope = Math.min(1, t * 90) * Math.exp(-t * 10);
      left = (Math.sin(2 * Math.PI * 880 * t) + Math.sin(2 * Math.PI * 1320 * t) * 0.25) * envelope * 0.42;
      right = left;
    } else if (definition.id === 'race-go') {
      const envelope = Math.min(1, t * 30) * Math.exp(-t * 4.5);
      left = (Math.sin(2 * Math.PI * 660 * t) * 0.35 + Math.sin(2 * Math.PI * 990 * t) * 0.24 + Math.sin(2 * Math.PI * 1320 * t) * 0.15) * envelope;
      right = (Math.sin(2 * Math.PI * 660 * t + 0.02) * 0.35 + Math.sin(2 * Math.PI * 990 * t + 0.02) * 0.24 + Math.sin(2 * Math.PI * 1320 * t + 0.02) * 0.15) * envelope;
    } else if (definition.id === 'ui-confirm') {
      const frequency = t < 0.1 ? 990 : 1480;
      const envelope = Math.sin(Math.PI * p) ** 0.65;
      left = Math.sin(2 * Math.PI * frequency * t) * envelope * 0.4;
      right = Math.sin(2 * Math.PI * frequency * t + 0.025) * envelope * 0.4;
    }
    raw[0][i] = Math.tanh(left * 1.15);
    raw[1][i] = Math.tanh(right * 1.15);
  }
  if (!definition.loop) return raw;
  const length = Math.round(definition.duration * MASTER_RATE);
  const fadeSamples = rawLength - length;
  const output = [new Float32Array(length), new Float32Array(length)];
  for (let channel = 0; channel < 2; channel += 1) {
    output[channel].set(raw[channel].subarray(0, length));
    for (let i = 0; i < fadeSamples; i += 1) {
      const mix = i / fadeSamples;
      output[channel][i] = raw[channel][length + i] * (1 - mix) + raw[channel][i] * mix;
    }
  }
  return output;
}

function normalize(channels) {
  let peak = 0;
  for (const channel of channels) for (const sample of channel) peak = Math.max(peak, Math.abs(sample));
  const gain = 10 ** (-1 / 20) / Math.max(peak, 0.0001);
  for (const channel of channels) for (let i = 0; i < channel.length; i += 1) channel[i] *= gain;
}

function resample(channels, targetRate) {
  const length = Math.round(channels[0].length * targetRate / MASTER_RATE);
  return channels.map((channel) => {
    const output = new Float32Array(length);
    for (let i = 0; i < length; i += 1) {
      const position = i * (channel.length - 1) / Math.max(1, length - 1);
      const left = Math.floor(position);
      const right = Math.min(channel.length - 1, left + 1);
      output[i] = lerp(channel[left], channel[right], position - left);
    }
    return output;
  });
}

function wavBuffer(channels, sampleRate, bits) {
  const bytes = bits / 8;
  const dataSize = channels[0].length * channels.length * bytes;
  const buffer = Buffer.alloc(44 + dataSize);
  buffer.write('RIFF', 0); buffer.writeUInt32LE(36 + dataSize, 4); buffer.write('WAVE', 8);
  buffer.write('fmt ', 12); buffer.writeUInt32LE(16, 16); buffer.writeUInt16LE(1, 20);
  buffer.writeUInt16LE(channels.length, 22); buffer.writeUInt32LE(sampleRate, 24);
  buffer.writeUInt32LE(sampleRate * channels.length * bytes, 28); buffer.writeUInt16LE(channels.length * bytes, 32);
  buffer.writeUInt16LE(bits, 34); buffer.write('data', 36); buffer.writeUInt32LE(dataSize, 40);
  let offset = 44;
  const scale = bits === 24 ? 8388607 : 32767;
  for (let i = 0; i < channels[0].length; i += 1) {
    for (let channel = 0; channel < channels.length; channel += 1) {
      const value = Math.round(clamp(channels[channel][i], -1, 1) * scale);
      if (bits === 24) buffer.writeIntLE(value, offset, 3);
      else buffer.writeInt16LE(value, offset);
      offset += bytes;
    }
  }
  return buffer;
}

function audioMetrics(channels) {
  let peak = 0; let sum = 0; let count = 0;
  for (const channel of channels) for (const sample of channel) { peak = Math.max(peak, Math.abs(sample)); sum += sample * sample; count += 1; }
  return { peak: round(peak, 5), rms: round(Math.sqrt(sum / count), 5) };
}

async function waveformSvg(channels, relative) {
  const bars = 96;
  const values = Array.from({ length: bars }, (_, bar) => {
    const start = Math.floor(bar / bars * channels[0].length);
    const end = Math.max(start + 1, Math.floor((bar + 1) / bars * channels[0].length));
    let peak = 0;
    const stride = Math.max(1, Math.floor((end - start) / 80));
    for (let i = start; i < end; i += stride) peak = Math.max(peak, Math.abs(channels[0][i]), Math.abs(channels[1][i]));
    return peak;
  });
  const content = values.map((value, index) => {
    const height = Math.max(1.5, value * 52);
    return `<rect x="${index * 5 + 1}" y="${fmt(32 - height / 2)}" width="2.6" height="${fmt(height)}" rx="1.3" opacity="${fmt(0.45 + value * 0.55)}"/>`;
  }).join('');
  await fs.writeFile(path.join(ROOT, 'public', relative), `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 480 64"><title>Audio waveform</title><g fill="#d7ff3f">${content}</g></svg>\n`);
}

async function buildAudio(definition) {
  const channels = synthesize(definition);
  normalize(channels);
  const runtime = resample(channels, RUNTIME_RATE);
  const masterRelative = `assets-src/audio/${definition.id}.wav`;
  const runtimeRelative = `assets/audio/runtime/${definition.id}.wav`;
  const waveformRelative = `assets/audio/waveforms/${definition.id}.svg`;
  await fs.writeFile(path.join(ROOT, masterRelative), wavBuffer(channels, MASTER_RATE, 24));
  await fs.writeFile(path.join(ROOT, 'public', runtimeRelative), wavBuffer(runtime, RUNTIME_RATE, 16));
  await waveformSvg(channels, waveformRelative);
  const metrics = audioMetrics(runtime);
  return {
    id: definition.id, name: definition.name, category: definition.category, description: definition.description,
    master: masterRelative, runtime: runtimeRelative, waveform: waveformRelative,
    duration: definition.duration, loop: definition.loop, loopStart: 0, loopEnd: definition.duration,
    sampleRate: RUNTIME_RATE, masterSampleRate: MASTER_RATE, bitDepth: 16, masterBitDepth: 24, channels: 2, format: 'PCM WAV',
    bytes: (await fs.stat(path.join(ROOT, 'public', runtimeRelative))).size, ...metrics, license: 'CC0-1.0',
  };
}

