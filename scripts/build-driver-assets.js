class GeometryBatch {
  constructor(parent) { this.parent = parent; this.batches = new Map(); }
  add(role, mat, geometry, matrix = new THREE.Matrix4()) {
    const transformed = geometry.index ? geometry.toNonIndexed() : geometry.clone();
    transformed.applyMatrix4(matrix);
    if (!transformed.getAttribute('normal')) transformed.computeVertexNormals();
    if (!transformed.getAttribute('uv')) transformed.setAttribute('uv', new THREE.Float32BufferAttribute(new Float32Array(transformed.getAttribute('position').count * 2), 2));
    const key = `${role}:${mat.uuid}`;
    if (!this.batches.has(key)) this.batches.set(key, { role, mat, geometries: [] });
    this.batches.get(key).geometries.push(transformed);
  }
  matrix(position, rotation = noRotation, scale = v(1, 1, 1)) { return new THREE.Matrix4().compose(position, new THREE.Quaternion().setFromEuler(rotation), scale); }
  box(role, mat, size, position, rotation = noRotation, bevel = 0) {
    const geometry = bevel ? new RoundedBoxGeometry(...size, bevel, Math.min(...size) * 0.12) : new THREE.BoxGeometry(...size);
    this.add(role, mat, geometry, this.matrix(position, rotation)); geometry.dispose();
  }
  capsule(role, mat, radius, length, detail, position, scale = v(1, 1, 1)) {
    const geometry = new THREE.CapsuleGeometry(radius, length, detail.caps, detail.segments);
    this.add(role, mat, geometry, this.matrix(position, noRotation, scale)); geometry.dispose();
  }
  sphere(role, mat, radius, detail, position, scale = v(1, 1, 1)) {
    const geometry = new THREE.SphereGeometry(radius, detail.segments, Math.max(5, Math.floor(detail.segments * 0.65)));
    this.add(role, mat, geometry, this.matrix(position, noRotation, scale)); geometry.dispose();
  }
  cylinder(role, mat, radii, height, detail, position, rotation = noRotation) {
    const geometry = new THREE.CylinderGeometry(radii[0], radii[1], height, detail.segments);
    this.add(role, mat, geometry, this.matrix(position, rotation)); geometry.dispose();
  }
  flush() {
    for (const { role, mat, geometries } of this.batches.values()) {
      const merged = mergeGeometries(geometries, false);
      if (!merged) throw new Error(`Unable to merge ${role}/${mat.name}`);
      const mesh = new THREE.Mesh(merged, mat); mesh.name = `${role}__${mat.name.replaceAll(' ', '_')}`; mesh.userData.velocityRole = role; this.parent.add(mesh);
      geometries.forEach((geometry) => geometry.dispose());
    }
    this.batches.clear();
  }
}
