function triangleCount(document) {
  let count = 0;
  // Count mesh instances on nodes: dedup() intentionally shares identical
  // geometry between left/right rigid parts, so unique meshes undercount draws.
  for (const node of document.getRoot().listNodes()) {
    const mesh = node.getMesh(); if (!mesh) continue;
    for (const primitive of mesh.listPrimitives()) {
      if ((primitive.getMode() ?? 4) !== 4) continue;
      const accessor = primitive.getIndices() || primitive.getAttribute('POSITION'); if (accessor) count += Math.floor(accessor.getCount() / 3);
    }
  }
  return count;
}
async function optimize(glb, outputPath, definition, lod) {
  const temporary = path.join(OUTPUT_DIR, `.tmp-${definition.id}-lod${lod}.glb`); await fs.writeFile(temporary, glb); const document = await io.read(temporary); await fs.rm(temporary);
  await document.transform(dedup(), weld(), prune({ keepLeaves: true }), meshopt({ encoder: MeshoptEncoder, level: 'high', quantizePosition: 16, quantizationVolume: 'mesh' }));
  const metadata = document.getRoot().getAsset().extras.velocityDriver || {};
  document.getRoot().getAsset().extras.velocityDriver = { ...metadata, lod, role: 'visual' };
  await io.write(outputPath, document); return { triangles: triangleCount(document), bytes: (await fs.stat(outputPath)).size };
}
