function createAnimations(joints) {
  const base = Object.fromEntries(Object.entries(joints).map(([name, node]) => [name, { quaternion: node.quaternion.clone(), position: node.position.clone() }]));
  const poses = {
    idle: { Chest: [0.015, 0, 0], Head: [0, 0.12, 0] },
    seated: {
      Pelvis: [0.08, 0, 0], ShoulderL: [-1.12, 0, -0.12], ShoulderR: [-1.12, 0, 0.12], ElbowL: [-0.5, 0, 0], ElbowR: [-0.5, 0, 0],
      HipL: [-1.35, 0, -0.05], HipR: [-1.35, 0, 0.05], KneeL: [1.35, 0, 0], KneeR: [1.35, 0, 0], AnkleL: [0.1, 0, 0], AnkleR: [0.1, 0, 0], Head: [-0.08, 0, 0],
    },
    celebrate: { ShoulderL: [0, 0, 2.65], ShoulderR: [0, 0, -2.65], ElbowL: [0, 0, 0.35], ElbowR: [0, 0, -0.35], Chest: [-0.08, 0, 0], Head: [-0.18, 0, 0] },
    signal: { ShoulderR: [-1.57, 0, 0], ElbowR: [0, 0, 0], WristR: [0, 0, 0], Head: [0, -0.22, 0], Chest: [0, -0.12, 0] },
  };
  const definitions = [
    { name: 'Idle', duration: 4, loop: true, times: [0, 2, 4], poses: [{}, poses.idle, {}], pelvisY: [0, 0.008, 0] },
    { name: 'Seated', duration: 2, loop: true, times: [0, 1, 2], poses: [poses.seated, poses.seated, poses.seated], pelvisY: [-0.23, -0.23, -0.23] },
    { name: 'Celebrate', duration: 2.4, loop: false, times: [0, 0.65, 1.35, 2.4], poses: [{}, poses.celebrate, poses.celebrate, {}], pelvisY: [0, 0.055, 0.02, 0] },
    { name: 'Signal', duration: 2, loop: false, times: [0, 0.55, 2], poses: [{}, poses.signal, poses.signal], pelvisY: [0, 0, 0] },
  ];
  return definitions.map((definition) => {
    const tracks = JOINTS.map((name) => {
      const values = [];
      for (const pose of definition.poses) {
        const delta = pose[name] || [0, 0, 0];
        const quaternion = base[name].quaternion.clone().multiply(new THREE.Quaternion().setFromEuler(new THREE.Euler(...delta)));
        values.push(...quaternion.toArray());
      }
      return new THREE.QuaternionKeyframeTrack(`${name}.quaternion`, definition.times, values);
    });
    const pelvisValues = definition.pelvisY.map((offset) => base.Pelvis.position.clone().add(v(0, offset, 0)).toArray()).flat();
    tracks.push(new THREE.VectorKeyframeTrack('Pelvis.position', definition.times, pelvisValues));
    return new THREE.AnimationClip(definition.name, definition.duration, tracks);
  });
}

