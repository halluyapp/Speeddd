async function exportGlb(scene) {
  const exporter = new GLTFExporter();
  const arrayBuffer = await exporter.parseAsync(scene, { binary: true, onlyVisible: true, trs: true });
  return Buffer.from(arrayBuffer);
}

function withAssetMetadata(glb, asset, lod, role) {
  const jsonLength = glb.readUInt32LE(12);
  const document = JSON.parse(glb.subarray(20, 20 + jsonLength).toString('utf8'));
  document.asset.generator = 'Velocity original procedural race-presentation pipeline';
  document.asset.copyright = `${asset.name}; Velocity original procedural asset; CC0 1.0 Universal`;
  document.asset.extras = {
    ...(document.asset.extras || {}),
    velocityRace: {
      pack: PACK_ID,
      id: asset.id,
      name: asset.name,
      license: 'CC0-1.0',
      source: CREDIT.source,
      units: 'metres',
      upAxis: '+Y',
      forwardAxis: '+Z',
      role,
      lod,
    },
  };
  const json = Buffer.from(JSON.stringify(document), 'utf8');
  const padded = Buffer.concat([json, Buffer.alloc((4 - json.length % 4) % 4, 0x20)]);
  const remaining = glb.subarray(20 + jsonLength);
  const output = Buffer.alloc(20 + padded.length + remaining.length);
  glb.copy(output, 0, 0, 20);
  output.writeUInt32LE(padded.length, 12);
  padded.copy(output, 20);
  remaining.copy(output, 20 + padded.length);
  output.writeUInt32LE(output.length, 8);
  return output;
}

function triangleCount(document) {
  let triangles = 0;
  // Count rendered node instances, not only unique mesh definitions. Dedup shares
  // identical lens geometry across nodes to reduce download size.
  for (const node of document.getRoot().listNodes()) {
    const mesh = node.getMesh();
    if (!mesh) continue;
    for (const primitive of mesh.listPrimitives()) {
      if ((primitive.getMode() ?? 4) !== 4) continue;
      const accessor = primitive.getIndices() || primitive.getAttribute('POSITION');
      if (accessor) triangles += Math.floor(accessor.getCount() / 3);
    }
  }
  return triangles;
}

async function optimize(glb, outputPath, asset, lod) {
  const temporary = path.join(OUTPUT_DIR, `.tmp-${asset.id}-lod${lod}.glb`);
  await fs.writeFile(temporary, glb);
  const document = await io.read(temporary);
  await fs.rm(temporary);
  await document.transform(
    dedup(),
    weld(),
    prune({ keepLeaves: true }),
    meshopt({ encoder: MeshoptEncoder, level: 'high', quantizePosition: 16, quantizationVolume: 'mesh' }),
  );
  const metadata = document.getRoot().getAsset().extras.velocityRace || {};
  document.getRoot().getAsset().extras.velocityRace = { ...metadata, lod, role: 'visual' };
  await io.write(outputPath, document);
  return { triangles: triangleCount(document), bytes: (await fs.stat(outputPath)).size };
}

function round(value) {
  return Math.round(value * 1000) / 1000;
}

function boundsRecord(scene) {
  const bounds = new THREE.Box3().setFromObject(scene);
  const size = bounds.getSize(new THREE.Vector3());
  const center = bounds.getCenter(new THREE.Vector3());
  const array = (vector) => [round(vector.x), round(vector.y), round(vector.z)];
  return { min: array(bounds.min), max: array(bounds.max), size: array(size), center: array(center) };
}

