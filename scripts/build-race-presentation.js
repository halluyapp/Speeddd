function pixelText(batch, role, mat, text, position, pixel = 0.04) {
  const value = text.toUpperCase();
  const width = Math.max(0, value.length * 6 - 1) * pixel;
  for (let charIndex = 0; charIndex < value.length; charIndex += 1) {
    const glyph = FONT[value[charIndex]];
    if (!glyph) continue;
    for (let row = 0; row < 7; row += 1) {
      for (let column = 0; column < 5; column += 1) {
        if (glyph[row][column] !== '1') continue;
        const geometry = new THREE.PlaneGeometry(pixel * 0.82, pixel * 0.82);
        const point = new THREE.Vector3(
          position.x - width / 2 + (charIndex * 6 + column + 0.5) * pixel,
          position.y + (3 - row) * pixel,
          position.z,
        );
        batch.add(role, mat, geometry, new THREE.Matrix4().makeTranslation(point.x, point.y, point.z));
        geometry.dispose();
      }
    }
  }
}

function brace(batch, from, to, radius = 0.045, segments = 8) {
  const direction = to.clone().sub(from);
  const geometry = new THREE.CylinderGeometry(radius, radius, direction.length(), segments);
  const quaternion = new THREE.Quaternion().setFromUnitVectors(new THREE.Vector3(0, 1, 0), direction.clone().normalize());
  const matrix = new THREE.Matrix4().compose(from.clone().add(to).multiplyScalar(0.5), quaternion, new THREE.Vector3(1, 1, 1));
  batch.add('frame', MAT.metal, geometry, matrix);
  geometry.dispose();
}

function addBolt(batch, position, segments) {
  batch.cylinder('hardware', MAT.metal, [0.055, 0.055], 0.045, segments, position, new THREE.Euler(Math.PI / 2, 0, 0));
}

